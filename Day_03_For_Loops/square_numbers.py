# square_numbers.py
# This script prints the squares of numbers from 1 to 10.

print("Squares of numbers from 1 to 10:")

for i in range(1, 11):
    square = i ** 2  # The ** operator is used for exponentiation (i squared)
    print(f"The square of {i} is {square}")

# beginner-friendly tip: You can also use i * i to calculate the square.
