# Printing data types of different variables

integer_val = 10
float_val = 10.5
string_val = "Hello Python"
boolean_val = True

print(f"Value: {integer_val}, Type: {type(integer_val)}")
print(f"Value: {float_val}, Type: {type(float_val)}")
print(f"Value: {string_val}, Type: {type(string_val)}")
print(f"Value: {boolean_val}, Type: {type(boolean_val)}")
